import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const provider = read('src/components/ui/ThemeProvider.tsx')
const pixelTransition = read('src/components/ui/BinaryPixelTransition.tsx')
const css = read('src/app/globals.css')

assert.match(provider, /doc\.startViewTransition/, 'theme toggle uses the View Transitions API')
assert.match(provider, /startViewTransition\(applyTheme\)/, 'theme mutation is captured between old and new snapshots')
assert.match(provider, /prefers-reduced-motion/, 'unsupported/reduced-motion path switches immediately')
assert.match(provider, /viewTransition\.finished/, 'transition state cleans up when reveal completes')
assert.match(css, /::view-transition-old\(root\)/, 'old theme snapshot remains visible below the wave')
assert.match(css, /::view-transition-new\(root\)/, 'new theme is progressively revealed above the wave')
assert.match(css, /clip-path:\s*circle\(0px at var\(--theme-origin-x\) var\(--theme-origin-y\)\)/, 'new theme begins at the toggle origin')
assert.match(css, /clip-path:\s*circle\(var\(--theme-reveal-radius\) at var\(--theme-origin-x\) var\(--theme-origin-y\)\)/, 'new theme expands to the farthest viewport corner')
assert.match(css, /::view-transition-old\(root\)\s*\{\s*animation-name:\s*none/, 'old theme stays visible below the wave')
assert.match(css, /html:active-view-transition[\s\S]*transition:\s*none/, 'normal color fades do not leak ahead of the wave')
assert.match(css, /animation-duration:\s*var\(--theme-transition-duration, 1400ms\)/, 'snapshot reveal uses the optimized shared duration')
assert.match(pixelTransition, /MIN_DURATION\s*=\s*1400/, 'canvas wave shares the 1.4 second duration')
assert.match(pixelTransition, /MAX_DURATION\s*=\s*1400/, 'canvas wave cannot drift from the reveal duration')
assert.match(css, /animation-timing-function:\s*cubic-bezier\(0\.22,\s*1,\s*0\.36,\s*1\)/, 'theme boundary starts quickly and eases slowly into the end')
assert.match(provider, /phase:\s*'reveal'\s*\|\s*'ripple'/, 'provider tracks a post-transition ripple phase')
assert.match(pixelTransition, /phase:\s*'reveal'\s*\|\s*'ripple'/, 'pixel transition supports the post-transition ripple phase')
assert.match(pixelTransition, /centres|centers|rippleCenters/, 'post-transition effect has multiple ripple centres')
assert.match(pixelTransition, /RIPPLE_DURATION/, 'post-transition ripple has a bounded duration')
assert.match(pixelTransition, /ripple.*Math\.hypot|Math\.hypot[\s\S]*ripple/, 'post-transition ripples use radial distance')
assert.match(pixelTransition, /cubicBezierProgress/, 'canvas uses the same cubic-bezier progress as the CSS reveal')
assert.doesNotMatch(pixelTransition, /1 - \(1 - rawProgress\) \*\* 4/, 'mismatched quartic reveal easing is removed')
assert.match(pixelTransition, /drawRing/, 'renderer visits bounded ring cells instead of scanning the full viewport grid')
assert.match(pixelTransition, /createRingField[\s\S]*cells\.sort/, 'grid distances are precomputed and sorted once per phase')
assert.match(pixelTransition, /const drawRing[\s\S]*lowerBound[\s\S]*for \(let index = from; index < to; index\+\+\)/, 'each frame visits only cells in the visible annulus')
assert.match(provider, /phase === 'ripple'/, 'only the post-transition ripple completion clears transition state')
console.log('wave-synchronized theme reveal contract: ok')
